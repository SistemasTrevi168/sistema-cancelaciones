const UNIONES = new Set(['DE', 'DEL', 'LA', 'LAS', 'LOS', 'Y']);
const clave = (p) => String(p || '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').toUpperCase().replace(/[^A-Z.]/g, '');

export function generoDeNombre(nombre) {
  const palabras = String(nombre || '').replace(/[._]/g, ' ').split(/\s+/).map(clave).filter(Boolean);
  if (!palabras.length) return '';
  // El primer nombre de pila conocido decide (aunque venga después de los apellidos: "PRADO NANCY")
  for (const p of palabras) {
    if (p === 'MA' || p === 'MA.') return 'FEMENINO';
    if (p === 'J' || p === 'J.') return 'MASCULINO';
    const h = HOMBRE.has(p); const m = MUJER.has(p);
    if (h && !m) return 'MASCULINO';
    if (m && !h) return 'FEMENINO';
    // nombre compartido, unión, apellido o palabra desconocida: se sigue con la siguiente
  }
  let primero = palabras.find((p) => !APELLIDOS.has(p) && !UNIONES.has(p)) || palabras[0];
  if (HOMBRE.has(primero) && MUJER.has(primero)) return ['GUADALUPE', 'ROSARIO'].includes(primero) ? 'FEMENINO' : 'MASCULINO';
  return primero.endsWith('A') ? 'FEMENINO' : 'MASCULINO';
}
